const assert=require('node:assert/strict'),{create}=require('../calculator-engine.js');
const c=require('../data/catalog.json'),{calculatorRecipe}=require('../catalog-api.js');
const recipes=c.recipes.map(calculatorRecipe).filter(Boolean);
assert.equal(recipes.length,792);
const ore=c.items.find(i=>i.name==='Hematite Ore');assert(ore);
const priced=price=>c.items.map(i=>({...i,ask:i.id===ore.id?price:null}));
const first=create(priced(100),recipes),second=create(priced(200),recipes);
const direct=recipes.find(r=>r.ingredients.length===1&&r.ingredients[0].itemId===ore.id);assert(direct);
const a=first.plan(direct.outputId,1,'craft'),b=second.plan(direct.outputId,1,'craft');
assert(a.cost>0);assert.equal(b.cost,2*a.cost);assert(first.affected(ore.id).includes(direct.outputId));
const fixture=[{id:'ore',ask:100},{id:'metal',ask:null},{id:'tool',ask:null}];
const chains=[{id:'metal',outputId:'metal',yield:2,ingredients:[{itemId:'ore',quantity:3}]},{id:'tool',outputId:'tool',yield:1,ingredients:[{itemId:'metal',quantity:3}]}];
assert.equal(create(fixture,chains).plan('tool',1).cost,600);
assert.deepEqual(create(fixture,chains).affected('ore'),['metal','tool']);
const alternatives=[...chains,{id:'expensive',outputId:'metal',yield:1,ingredients:[{itemId:'ore',quantity:10}]}];
assert.equal(create(fixture,alternatives).plan('tool',1).cost,600);
const cycle=[{outputId:'ore',yield:1,ingredients:[{itemId:'tool',quantity:1}]},...chains];
assert.equal(create(fixture,cycle).plan('tool',1).cost,600);
assert.equal(create([{id:'tool',ask:10}], [{outputId:'tool',yield:1,ingredients:[{itemId:'missing',quantity:1}]}]).plan('tool',1).cost,10);
assert.throws(()=>create([{id:'x',ask:null}],[]).plan('x',1),/missing/);
console.log('PASS: actual Hematite repricing, 792 base recipes, recursive batches, alternatives, cycles with purchase route, unknown inputs');
